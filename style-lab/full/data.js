export const formatMoney = (value) => {
  if (value == null) return "по смете";
  return new Intl.NumberFormat("ru-RU").format(value) + " ₽";
};

export function getService(slug) {
  const direct = services.find((item) => item.slug === slug);
  if (direct) return direct;
  const discipline = disciplines.find((item) => item.slug === slug);
  if (!discipline) return null;
  const parent = services.find((item) => item.slug === discipline.parent);
  return {
    ...parent,
    slug: discipline.slug,
    title: discipline.title,
    eyebrow: "С учётом направления",
    short: discipline.note,
    from: discipline.from,
    note: `${discipline.note} Итоговый состав работ редактор определит после просмотра материалов.`
  };
}

