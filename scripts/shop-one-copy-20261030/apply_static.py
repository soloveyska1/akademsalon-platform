MONEY = "  const money = value => Number(value).toLocaleString('ru-RU') + ' ₽';"
HELPERS = ("  const stockLabel = p => p.available ? 'В продаже' : p.reserved ? 'Сейчас оформляют' "
           ": p.sold ? 'Продано' : 'Нет в продаже';",
           "  const copiesNote = p => Number(p.licences) === 1 ? 'Один экземпляр: после оплаты работа снимается "
           "с продажи' : `Экземпляров в продаже: ${Number(p.available)} из ${Number(p.licences)}`;")
JS_LINK = re.compile(r'(/assets/js/material-store\.js\?v=)[^"&]+(&(?:amp;)?r=)[0-9a-f]{16}')


def read(path):
    return path.read_bytes().decode("utf-8")


def write(path, text):
    path.write_bytes(text.encode("utf-8"))


def replace_all(name, text, pairs):
    for old, new in pairs:
        if text.count(new) == 1 and old not in text:
            continue
        assert text.count(old) == 1, f"{name}: ожидалось одно вхождение: {old[:70]}…"
        text = text.replace(old, new)
    return text


def main(root):
    js_path = root / "assets/js/material-store.js"
    js = replace_all("material-store.js", read(js_path), JS)
    if "const stockLabel" not in js:
        assert js.count(MONEY) == 1, "material-store.js: не найдена строка money"
        eol = "\r\n" if "\r\n" in js else "\n"
        js = js.replace(MONEY, eol.join((MONEY,) + HELPERS))
    write(js_path, js)
    # Хэш — от содержимого с LF, как его хранит git и как он лежит на сервере.
    digest = hashlib.sha256(js.replace("\r\n", "\n").encode("utf-8")).hexdigest()[:16]

    shop_path = root / "shop.html"
    shop = replace_all("shop.html", read(shop_path), SHOP)
    assert len(JS_LINK.findall(shop)) == 1, "shop.html: ссылка на material-store.js"
    shop = JS_LINK.sub(lambda m: f"{m.group(1)}{JS_VER}{m.group(2)}{digest}", shop)
    write(shop_path, shop)

    terms_path = root / "shop-terms.html"
    write(terms_path, replace_all("shop-terms.html", read(terms_path), TERMS))

    for name, text in (("shop.html", shop), ("shop-terms.html", read(terms_path)), ("material-store.js", js)):
        for word in ("неэксклюз", "неисключ", "тираж", "нескольк"):
            assert word not in text.lower(), f"{name}: осталось «{word}»"
    print(f"material-store.js r={digest}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
